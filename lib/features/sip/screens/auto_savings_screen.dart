  String _formatDate(String dateStr) {
    try {
      final parts = dateStr.split('-');
      if (parts.length != 3) return dateStr;
      final months = [
        '',
        'Jan',
        'Feb',
        'Mar',
        'Apr',
        'May',
        'Jun',
        'Jul',
        'Aug',
        'Sep',
        'Oct',
        'Nov',
        'Dec'
      ];
      final day = int.parse(parts[2]);
      final month = int.parse(parts[1]);
      final year = parts[0];
      return '$day ${months[month]} $year';
    } catch (_) {
      return dateStr;
    }
  }

