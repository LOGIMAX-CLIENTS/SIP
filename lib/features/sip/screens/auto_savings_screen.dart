                              fontWeight: (isActive || isCommitted)
                                  ? FontWeight.w700
                                  : FontWeight.w500,
                              color: isActive
                                  ? Colors.white
                                  : (isCommitted
                                      ? const Color(0xFFD97706)
                                      : const Color(0xFF1A1A2E)),
                            ),
                          ),
                        ),
                      ),
                    );
                  },
                ),
                SizedBox(height: 16.h),
                SafeArea(
                  top: false,
